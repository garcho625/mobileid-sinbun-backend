import assert from 'node:assert/strict';
import { keys, sign } from '../lib/proof.ts';
import { deviceKeys } from '../lib/offline-store.ts';
import { makeRequest, respondQr, checkQr, parseQr, encodeQr, QR_MAX_BYTES } from '../lib/qr-proof.ts';
const issuer=await keys(), device=await deviceKeys(), now=Date.now();
assert.equal(device.privateKey.extractable,false);
await assert.rejects(crypto.subtle.exportKey('jwk',device.privateKey));
const credential=await sign({id:crypto.randomUUID(),name:'테스트 방문자',deviceKey:device.publicKey,issued:now,expires:now+3600000},issuer.privateKey);
const trust={publicKey:issuer.publicKey,prepared:now};
const request=makeRequest(crypto.randomUUID());
const response=await respondQr(request,credential,device);
assert((await checkQr(request,parseQr(encodeQr(response),'ansim-response'),trust)).every(c=>c.ok));
assert(!encodeQr(response).includes('privateKey'));
assert(new TextEncoder().encode(encodeQr(response)).length<=QR_MAX_BYTES);
for(const changes of [{sessionId:crypto.randomUUID()},{verifierId:crypto.randomUUID()},{nonce:crypto.randomUUID()},{expiresAt:request.expiresAt-1000}])assert((await checkQr({...request,...changes},response,trust)).some(c=>!c.ok));
const tampered=structuredClone(response);tampered.credential.payload.name='tampered';
assert(!(await checkQr(request,tampered,trust))[0].ok);
const forged=structuredClone(response);forged.response.payload.sessionId=crypto.randomUUID();
assert((await checkQr(request,forged,trust)).some(c=>!c.ok));
assert(!(await checkQr(request,response,trust,request.expiresAt)).at(-1).ok);
assert.throws(()=>parseQr('x'.repeat(1501),'ansim-request'));
assert.throws(()=>parseQr(JSON.stringify({...request,v:2}),'ansim-request'));
assert.throws(()=>parseQr(encodeQr(response),'ansim-request'));
assert.throws(()=>parseQr(JSON.stringify({...response,credential:{...credential,payload:{...credential.payload,deviceKey:issuer.privateKey}}}),'ansim-response'));
await assert.rejects(respondQr({...request,expiresAt:now-1},credential,device));
console.log('PASS: nonextractable device key, QR roundtrip/size/no private key, session/verifier/nonce/time binding, tamper/signature/expiry/version/type/private key rejection');
